// Top edge of the painted ground. The stretch behind the suit is interpolated.
const edge=[[-400,786],[47,853],[60,855],[75,864],[89,850],[106,839],[125,838],
  [145,855],[162,868],[179,855],[196,861],[259,879],[460,910],[650,942],
  [680,946],[697,945],[717,948],[736,954],[752,945],[772,940],[790,936],
  [799,940],[808,949],[827,954],[850,965],[878,976],[904,982],[935,995],
  [954,999],[970,996],[989,1000],[1017,1008],[1043,1013],[1070,1012],
  [1100,1020],[1240,1044],[1650,1112]];
export function horizonY(x){
  let lo=0,hi=edge.length-1;
  while(hi-lo>1){
    const m=(lo+hi)>>1;
    if(x<edge[m][0])hi=m;else lo=m;
  }
  const [a,y]=edge[lo],[b,z]=edge[hi];
  return y+(z-y)*Math.min(1,Math.max(0,(x-a)/(b-a)));
}
